// Derive client parameter names/types from the versioned SQL; never introspect a remote project.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const definitions = {};
for (const file of readdirSync('supabase/migrations').filter(f => f.endsWith('.sql')).sort()) {
 const sql=readFileSync(`supabase/migrations/${file}`,'utf8');
 for (const [,name,args] of sql.matchAll(/CREATE FUNCTION public\.(\w+)\((.*?)\) RETURNS/gs)) {
  if(name.startsWith('svc_') || ['prepare_asset','authorize_asset_read'].includes(name)) continue;
  definitions[name]=args.split(',').map(x=>x.trim()).filter(Boolean).map(arg=>{
   const [,key,type,rest]=arg.match(/^(\w+)\s+(\w+(?:\[\])?)(.*)$/s);
   return {key,type,optional:/DEFAULT/i.test(rest)};
  });
 }
}
const tsType=t=>t==='boolean'?'boolean':/^(integer|bigint|smallint)$/.test(t)?'number':t==='jsonb'?'Json':t==='text[]'?'string[]':'string';
const output=`// Generated by scripts/generate-web-contracts.mjs from local migrations.\nexport type Json = null | boolean | number | string | Json[] | { [key: string]: Json };\nexport interface RpcArguments {\n${Object.entries(definitions).map(([name,args])=>`  ${name}: { ${args.map(a=>`${a.key}${a.optional?'?':''}: ${tsType(a.type)}${a.optional?' | null':''}`).join('; ')} };`).join('\n')}\n}\nexport type RpcName = keyof RpcArguments;\nexport const parameters = ${JSON.stringify(definitions,null,2)} as const;\n`;
const target='apps/academy-admin/src/connect/contracts.ts';
if(process.argv.includes('--check')) {
 if(readFileSync(target,'utf8')!==output) throw new Error('Web contracts differ from migrations; run npm run generate:web');
} else writeFileSync(target,output);
